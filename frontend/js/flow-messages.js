export function localizeMessage(text) {
 const vi = Object.hasOwn(messages, text) ? text : Object.keys(messages).find(key => messages[key] === text);
 if (vi) return translate(vi, messages[vi]);
 if (typeof text !== 'string') return text;
 // Validation can combine several known messages. Translate each sentence,
 // while leaving server-provided details and attendee data intact.
 for (const [source, target] of Object.entries(messages).map(([vi, en]) => getLanguage() === 'en' ? [vi, en] : [en, vi]).sort((a, b) => b[0].length - a[0].length)) {
   if (text.includes(source)) text = text.split(source).join(target);
 }
 return text;
}
